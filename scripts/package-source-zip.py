#!/usr/bin/env python3
"""
Package the portfolio source code into a clean, portable ZIP file.

Excludes:
  - node_modules/ (huge, regenerated by `bun install`)
  - .next/ (build output)
  - .git/ (would conflict with the user's own git init)
  - .env, .env.* (secrets)
  - db/custom.db (local SQLite database)
  - .zscripts/ (sandbox-internal orchestration)
  - download/ (sandbox deliverables folder)
  - skills/ (skill definitions, not part of the project)
  - worklog.md, dev.log, server.log, service.log, *.pid (runtime files)
  - scripts/start-contact-service.py (sandbox-only helper)

Includes:
  - All source code (src/, mini-services/, prisma/, public/)
  - Configs (package.json, tsconfig.json, next.config.ts, etc.)
  - The generated resume PDF
  - .gitignore, .env.example, README.md
  - The chat API route + chatbot UI
  - All portfolio components
"""
import os
import zipfile
import sys
from pathlib import Path

PROJECT_DIR = Path("/home/z/my-project")
OUTPUT_ZIP = Path("/home/z/my-project/download/dires-portfolio-source.zip")

# === Files and directories to exclude (matched against the relative path) ===
EXCLUDE_DIRS = {
    "node_modules",
    ".next",
    ".git",
    ".zscripts",
    "skills",
    "download",
    "db",
    "examples",
    "tests",
    "__pycache__",
    ".turbo",
    ".cache",
}

EXCLUDE_FILES = {
    ".env",
    ".env.local",
    ".env.development",
    ".env.production",
    "dev.log",
    "dev.out.log",
    "server.log",
    "service.log",
    "worklog.md",
    "dev.pid",
    "service.pid",
    "custom.db",
    "db.lock",
    ".DS_Store",
    "Thumbs.db",
}

EXCLUDE_FILE_PATTERNS = (
    ".log",
    ".pid",
    ".tsbuildinfo",
    ".map",
)

# Files that should be at the zip root (we'll add a couple of helpful ones)
