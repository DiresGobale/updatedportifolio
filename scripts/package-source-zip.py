def should_exclude(path: Path) -> bool:
    """Return True if the given path (relative to PROJECT_DIR) should be excluded."""
    rel = path.relative_to(PROJECT_DIR)
    parts = rel.parts

    # Exclude if any path component is in EXCLUDE_DIRS
    for part in parts:
        if part in EXCLUDE_DIRS:
            return True

    # Exclude specific files
    if path.name in EXCLUDE_FILES:
        return True

    # Exclude by file extension patterns
    for pat in EXCLUDE_FILE_PATTERNS:
        if path.name.endswith(pat):
            return True

    return False


def main():
    # Make sure the output directory exists
    OUTPUT_ZIP.parent.mkdir(parents=True, exist_ok=True)

    # Remove any previous zip
    if OUTPUT_ZIP.exists():
        OUTPUT_ZIP.unlink()

    file_count = 0
    total_bytes = 0

    with zipfile.ZipFile(OUTPUT_ZIP, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as zf:
        # Walk the project directory
        for root, dirs, files in os.walk(PROJECT_DIR):
            root_path = Path(root)

            # Skip excluded directories in-place (modifies `dirs` so os.walk
            # doesn't descend into them)
            dirs[:] = [d for d in dirs if d not in EXCLUDE_DIRS]

            for filename in files:
                file_path = root_path / filename
                if should_exclude(file_path):
                    continue

                # Compute the archive path (relative to project root, inside a
                # top-level folder named "dires-portfolio" so the zip extracts
                # cleanly into a single folder)
                rel_path = file_path.relative_to(PROJECT_DIR)
                archive_path = str(Path("dires-portfolio") / rel_path)

                zf.write(file_path, archive_path)
                file_count += 1
                total_bytes += file_path.stat().st_size

        # Add a README.md at the zip root
        zf.writestr("dires-portfolio/README.md", EXTRA_README_CONTENT)

    # Verify
    zip_size = OUTPUT_ZIP.stat().st_size
    print(f"ZIP created: {OUTPUT_ZIP}")
    print(f"Files included: {file_count + 1} (incl. README.md)")
    print(f"Uncompressed size: {total_bytes / 1024 / 1024:.1f} MB")
    print(f"Compressed size: {zip_size / 1024 / 1024:.1f} MB")

    # List a sample of included files for verification
    with zipfile.ZipFile(OUTPUT_ZIP, "r") as zf:
        names = zf.namelist()
        print(f"\nSample of included files (first 25):")
        for n in sorted(names)[:25]:
            print(f"  {n}")
        if len(names) > 25:
            print(f"  ... and {len(names) - 25} more")


if __name__ == "__main__":
    main()
